-- The WP monad.

type TM = Except StructError

type Decls = Map Text (Maybe Expr)

type WP =
  RWST
    (Decls, [[Text]], [FootPrint])
    ([PO], [Spec], [StructWarning], IntMap (Int, Expr))
    Int
    TM

instance Counterous WP where
  countUp = do
    i <- get
    put (succ i)
    return i


-- will be constructed by groupStmts
data SegElm
  = SAsrt Stmt
  | SSpec Stmt
  | SStmts [Stmt]

-- types of mutually recursive functions

type TstructStmts = InfMode -> (Pred, Maybe Expr) -> [Stmt] -> Pred -> WP ()

type TstructSegs = (Pred, Maybe Expr) -> [SegElm] -> Pred -> WP ()

type Tstruct = (Pred, Maybe Expr) -> Stmt -> Pred -> WP ()

type TwpSegs = [SegElm] -> Pred -> WP Pred

type TwpSStmts = [Stmt] -> Pred -> WP Pred

type Twp = Stmt -> Pred -> WP Pred

type TspStmts = (Pred, Maybe Expr) -> [Stmt] -> WP Pred

type TspSegs = (Pred, Maybe Expr) -> [SegElm] -> WP Pred

type TspSStmts = (Pred, Maybe Expr) -> [Stmt] -> WP Pred

-- information generated by WP-related modules

data FootPrint
  = IfTotal (Maybe Range)
  | IfBranch (Maybe Range)
  | LoopInvBase (Maybe Range)
  | LoopInvInd (Maybe Range)
  | LoopTermBase (Maybe Range)
  | LoopTermInd (Maybe Range)
  deriving (Eq, Show, Generic)

data StructWarning
  = MissingBound Range
  deriving (Eq, Show, Generic)

instance MaybeRanged StructWarning where
  maybeRangeOf (MissingBound rng) = Just rng

data StructError
  = MissingInvariant (Maybe Range)
  | MissingPostcondition (Maybe Range)
  | MultiDimArrayAsgnNotImp (Maybe Range)
  | -- Assignment to multi-dimensional array not implemented.
    -- SCM: will remove this when we figure out how.
    LocalVarExceedScope (Maybe Range)
  deriving (Eq, Show, Generic)

instance MaybeRanged StructError where
  maybeRangeOf (MissingInvariant l) = l
  maybeRangeOf (MissingPostcondition l) = l
  maybeRangeOf (MultiDimArrayAsgnNotImp l) = l
  maybeRangeOf (LocalVarExceedScope l) = l

-- | A predicate is an expression, whose type happens to be Bool.
type Pred = Expr

-- | Proof obligation
data PO = PO
  { poPred :: Pred, -- a single proposition
    poReducedPred :: Pred, -- display-only reduction state
    poStrippedPred :: Text, -- pred without surrounding rendered html
    poProofExists :: Bool,
    poSMTResult :: Text,
    poAnchorRange :: Maybe Range, -- anchor location, if it exists in the source
    poFootPrints :: [FootPrint],
    poOrigin :: Maybe Range -- whereabouts
  }
  deriving (Eq, Show, Generic)

instance Ord PO where
  compare x y = compare (poOrigin y) (poOrigin x)

instance MaybeRanged PO where
  maybeRangeOf = poOrigin

data InfMode
  = Primary -- the main inference mode
  | Secondary -- non-functional postconditions. ignore assertions
  deriving (Eq, Show, Generic)

instance ToJSON InfMode
